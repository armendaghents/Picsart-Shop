function resolve(entry, params) {
  if (typeof entry === "function") return entry(params || {});
  return entry;
}

// Errors arrive from the API already worded in English. The `error` code (and,
// for validation, the per-field `problems` codes) is what stays stable across
// languages, so that is what gets looked up here; the server's own wording is
// only the last resort for a code this bundle doesn't know yet.
export function errorMessage(t, error) {
  if (!error) return "";

  const problems = error.data?.problems;
  if (Array.isArray(problems) && problems.length) {
    const translated = problems.map((problem) => resolve(t.problems[problem.code], problem.params));
    if (translated.every(Boolean)) return translated.join(" ");
  }

  const known = resolve(t.errors[error.code], error.data);
  if (known) return known;

  return error.message || t.errors.generic;
}
