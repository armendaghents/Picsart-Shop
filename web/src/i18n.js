// English pluralisation: one form vs. everything else.
function en(n, one, other) {
  return n === 1 ? one : other;
}

// Russian pluralisation: 1 товар / 2 товара / 5 товаров, with the 11–14
// exception that trips up the naive "ends in 1" rule.
function ru(n, one, few, many) {
  const mod10 = Math.abs(n) % 10;
  const mod100 = Math.abs(n) % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

